"""Purpose: write index.html from mockups.src.html with palettes.css and mockup.css inlined, so the page opens on its
own with nothing fetched (manual 2.3.8.4). Spike tool (global Rule 4).
Usage: python3 spikes/webui-palette/build.py"""
from pathlib import Path

HERE = Path(__file__).parent


def main():
    """Inline each local stylesheet link and write index.html."""
    page = (HERE / "mockups.src.html").read_text()
    for name in ("palettes.css", "mockup.css"):
        link = f'<link rel="stylesheet" href="{name}">'
        if link not in page:
            raise SystemExit(f"mockups.src.html has no {link}")
        page = page.replace(link, f"<style>/* {name} */\n{(HERE / name).read_text()}</style>")
    page = page.replace("<!-- spikes/webui-palette (manual 2.3.8.4): the source of index.html.",
                        "<!-- spikes/webui-palette (manual 2.3.8.4): GENERATED by build.py from mockups.src.html.")
    (HERE / "index.html").write_text(page)
    print("wrote", HERE / "index.html")


if __name__ == "__main__":
    main()
