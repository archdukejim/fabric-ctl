import subprocess

from fabriclib.common.errors import ValidationError
from fabriclib.localadmin.common.bao_call import bao_call
from fabriclib.localadmin.common.utc_now import utc_now
from fabriclib.localadmin.constants import MAX_VERSIONS, MOUNT, PASSWORD_POLICY, USER
from fabriclib.localadmin.secret_path import secret_path


def _chpasswd(user, password):
    """Purpose: a local account's password set on this host, on stdin (never a command line).
    Inputs:  user — the account; password — str.
    Returns: None.
    Fails:   ValidationError with chpasswd's complaint; OSError without chpasswd.
    Feeds:   set_local_admin_password (its default)."""
    res = subprocess.run(["chpasswd"], input=f"{user}:{password}\n", capture_output=True, text=True, timeout=60)
    if res.returncode != 0:
        raise ValidationError((res.stderr or res.stdout).strip()[-300:] or f"chpasswd: exit {res.returncode}")


def set_local_admin_password(v, token, reason, policy, set_password=_chpasswd, now=utc_now):
    """Purpose: a new password for the fabric host's local-admin (manual 1.7.1.4.2): generated by OpenBao's password
             policy, written to OpenBao as a new version first, then set on the host, and only then marked current in
             the path's metadata. A failure between leaves the old password working and current (1.7.1.3.3).
    Inputs:  v — vars (OpenBao's address, site_name, hostname); token — a fabric-setup token; reason — "initial" or
             "after use" (1.7.1.3.2); policy — the rotation policy recorded with it; set_password — callable(user,
             password) that sets it on the host (default chpasswd; tests give their own); now — the clock.
    Returns: {"version": int, "set_at": ISO str} — the version now current.
    Fails:   ValidationError: OpenBao refused or did not answer (nothing changed on the host); the host did not take it
             ("the host did not take the new password: …", the old one still valid and current, the new version left
             unmarked).
    Feeds:   setup/setup_local_admin (initial), check_local_admin (after use); tests/openbao/local_admin.py."""
    path = secret_path(v)
    password = bao_call(v, token, "GET", f"sys/policies/password/{PASSWORD_POLICY}/generate")["data"]["password"]
    stamp = now().isoformat()
    written = bao_call(v, token, "POST", f"{MOUNT}/data/{path}", {"data": {
        "password": password, "set_on": stamp, "reason": reason, "host": v["hostname"].lower()}})
    version = written["data"]["version"]
    try:
        set_password(USER, password)
    except (ValidationError, OSError) as e:
        raise ValidationError(f"the host did not take the new password: {e}; the old one stays valid and current "
                              f"(OpenBao's version {version} is not marked current)")
    bao_call(v, token, "POST", f"{MOUNT}/metadata/{path}", {
        "max_versions": MAX_VERSIONS,
        "custom_metadata": {"current": str(version), "policy": policy, "set_on": stamp, "reason": reason}})
    return {"version": version, "set_at": stamp}
